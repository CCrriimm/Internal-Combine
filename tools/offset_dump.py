#!/usr/bin/env python3
"""BloodStrike offset dumper.

Outputs:
  offsets.json      - SDK classes/members with offsets and sizes
  game_offsets.h    - C++ constants for selected classes
  offset_report.txt - human readable report, including Python bridge checks

The Python bridge RVAs below are module-relative (BloodStrike.exe image base
0x140000000). They are validated against known x64 prologues so a game update
is caught before injection.
"""
from __future__ import annotations

import argparse
import json
import struct
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SDK = str(PROJECT_ROOT / 'reference' / 'offsets' / 'SDK.json')
DEFAULT_OUT = str(PROJECT_ROOT / 'reports' / 'offsets')

PY_OFFSETS = {
    "PyGILState_Ensure": (0x2ADC1C0, "48895c2410574883ec20488d0d"),
    "PyGILState_Release": (0x2ADC290, "48895c2410574883ec208bf9488d0d"),
    "PyRun_SimpleStringFlags": (0x2A9DEE0, "48895c24084889742410574883ec40488bf1488bda"),
}

HEADER_CLASSES = [
    "ClientPlayer",
    "EntityDetector",
    "IEntity",
    "PhysicsSpaceDisplayerComponent",
    "RecastMapDisplayerComponent",
]


class PE:
    def __init__(self, path: str):
        self.path = path
        self.data = Path(path).read_bytes()
        e = struct.unpack_from("<I", self.data, 0x3C)[0]
        if self.data[e:e + 4] != b"PE\0\0":
            raise ValueError("not a PE file")
        nsec = struct.unpack_from("<H", self.data, e + 6)[0]
        optsz = struct.unpack_from("<H", self.data, e + 20)[0]
        opt = e + 24
        self.image_base = struct.unpack_from("<Q", self.data, opt + 24)[0]
        sec = opt + optsz
        self.sections = []
        for i in range(nsec):
            o = sec + i * 40
            name = self.data[o:o + 8].rstrip(b"\0").decode("latin1")
            vsz, va, rsz, raw = struct.unpack_from("<IIII", self.data, o + 8)
            self.sections.append((name, va, vsz, raw, rsz))

    def rva_to_off(self, rva: int):
        for _, va, vsz, raw, rsz in self.sections:
            if va <= rva < va + max(vsz, rsz):
                return raw + (rva - va)
        return None

    def read_rva(self, rva: int, n: int) -> bytes:
        off = self.rva_to_off(rva)
        if off is None:
            return b""
        return self.data[off:off + n]

    def check_python(self):
        rows = []
        ok = True
        for name, (rva, prefix) in PY_OFFSETS.items():
            got = self.read_rva(rva, len(prefix) // 2).hex()
            good = got.startswith(prefix.lower())
            ok = ok and good
            rows.append((name, rva, good, got, prefix.lower()))
        return ok, rows


def type_name(t) -> str:
    if not isinstance(t, dict):
        return str(t)
    base = t.get("type", "")
    sub = t.get("subtypes")
    if sub:
        return "%s<%s>" % (base, ",".join(type_name(x) for x in sub))
    return base


def dump_sdk(sdk_path: str, out_dir: Path):
    sdk = json.loads(Path(sdk_path).read_text(encoding="utf-8"))
    classes = {}
    for c in sdk.get("classes", []):
        name = c.get("name")
        if not name:
            continue
        classes[name] = {
            "size": c.get("size", 0),
            "inherits": c.get("inherits", []),
            "members": {
                m.get("name", ""): {
                    "offset": m.get("offset", 0),
                    "size": m.get("size", 0),
                    "type": type_name(m.get("type")),
                    "array_dim": m.get("arrayDim", 1),
                }
                for m in c.get("members", [])
                if m.get("name")
            },
        }
    (out_dir / "offsets.json").write_text(
        json.dumps(
            {
                "game": sdk.get("game", ""),
                "version": sdk.get("version", ""),
                "classes": classes,
            },
            indent=2,
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )

    lines = [
        "// Generated by tools/offset_dump.py. Do not edit by hand.",
        "#pragma once",
        "#include <cstdint>",
        "",
    ]
    for cname in HEADER_CLASSES:
        c = classes.get(cname)
        if not c:
            continue
        lines.append("namespace %s {" % cname)
        lines.append("constexpr uint32_t kSize = %du;" % c["size"])
        for mname, m in c["members"].items():
            ident = "".join(ch if ch.isalnum() else "_" for ch in mname)
            lines.append("constexpr uint32_t k%s = %du;" % (ident, m["offset"]))
        lines.append("}  // namespace %s" % cname)
        lines.append("")
    (out_dir / "game_offsets.h").write_text("\n".join(lines), encoding="utf-8")
    return sdk, classes


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--exe", required=True, help="Path to the installed BloodStrike executable")
    ap.add_argument("--sdk", default=DEFAULT_SDK)
    ap.add_argument("--out", default=DEFAULT_OUT)
    args = ap.parse_args()
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    report = []
    pe = PE(args.exe)
    report.append("exe: %s" % Path(args.exe).name)
    report.append("size: %d bytes" % len(pe.data))
    report.append("image base: 0x%X" % pe.image_base)
    report.append("sections: %s" % ", ".join(s[0] for s in pe.sections))
    report.append("")

    py_ok, rows = pe.check_python()
    report.append("python bridge: %s" % ("OK" if py_ok else "MISMATCH"))
    for name, rva, good, got, want in rows:
        report.append(
            "  %-24s rva=0x%X file=0x%X %s got=%s want=%s"
            % (
                name,
                rva,
                pe.rva_to_off(rva) or 0,
                "OK" if good else "BAD",
                got,
                want,
            )
        )
    report.append("")

    sdk, classes = dump_sdk(args.sdk, out_dir)
    report.append("sdk: %s" % (Path(args.sdk).resolve().relative_to(PROJECT_ROOT).as_posix() if Path(args.sdk).resolve().is_relative_to(PROJECT_ROOT) else Path(args.sdk).name))
    report.append("game: %s" % sdk.get("game", ""))
    report.append("version: %s" % sdk.get("version", ""))
    report.append("classes: %d" % len(classes))
    report.append("")
    for cname in HEADER_CLASSES:
        c = classes.get(cname)
        if not c:
            continue
        report.append("%s size=%d members=%d" % (cname, c["size"], len(c["members"])))
        for mname, m in c["members"].items():
            report.append("  +0x%04X %-40s %s" % (m["offset"], mname, m["type"]))
        report.append("")

    (out_dir / "offset_report.txt").write_text("\n".join(report), encoding="utf-8")
    print("\n".join(report))
    return 0 if py_ok else 2


if __name__ == "__main__":
    sys.exit(main())
